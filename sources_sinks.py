def plot_forced_sink_efficiency(data, box):
    """
    Plots the seasonal flux magnitude alongside the raw accumulating concentration 
    to show how sink capacity changes while CO2 constantly increases.
    """
    # 1. Isolate and process the raw concentration data
    data_box = data.sel(lat=slice(box.lat0, box.lat1), lon=slice(box.lon0, box.lon1))
    raw_concentration = data_box.mean(dim=['lat', 'lon'])
    
    # Extract variable assuming it's named 'CO2' or similar
    co2_var = convert_ppm(raw_concentration, key=None)["CO2"]
    
    # 2. Calculate the monthly change (Flux)
    monthly_flux = co2_var.diff(dim='time')

    # 3. Setup a 2-panel plot with a shared X-axis
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(15, 10), sharex=True)

    # ----------------------------------------------------
    # TOP PANEL: The Constantly Increasing Background CO2
    # ----------------------------------------------------
    co2_var.plot.line(ax=ax1, color='black', linewidth=2.5, label="Atmospheric CO2 Concentration")
    
    # Fit a single trendline over the constant increase
    fit_raw = co2_var.polyfit(dim="time", deg=1)
    var_key = list(fit_raw.data_vars)[0]
    xr.polyval(co2_var.time, fit_raw[var_key]).plot.line(
        ax=ax1, color='tab:red', linestyle='--', alpha=0.8, label="Forced Linear Trend"
    )
    
    ax1.set_title(f"Carbon Sink Stress Testing in {box.name} (Forced Growth Phase)", fontsize=14, fontweight='bold')
    ax1.set_ylabel("Total CO2 Concentration (ppm)")
    ax1.legend(loc="upper left")
    ax1.grid(True, alpha=0.3)

    # ----------------------------------------------------
    # BOTTOM PANEL: The Seasonal Flux Variations
    # ----------------------------------------------------
    # Group by year to look at the maximum summer sink drawdown vs winter release
    yearly_source_max = monthly_flux.groupby('time.year').max(dim='time')
    yearly_sink_min = monthly_flux.groupby('time.year').min(dim='time')

    # Convert the year index to matching datetime coordinate format for alignment
    years_dt = [np.datetime64(f"{y}-06-15") for y in yearly_source_max.year.values]
    
    ax2.plot(years_dt, yearly_source_max.values, marker='o', color='tab:red', label="Winter Source Peak")
    ax2.plot(years_dt, yearly_sink_min.values, marker='s', color='tab:green', label="Summer Sink Trough")

    # Fit trends to the seasonal extremes to see if they are changing behavior
    for dataset, trend_color, label_name in [(yearly_source_max, 'darkred', 'Source Change'), (yearly_sink_min, 'darkgreen', 'Sink Change')]:
        fit_extreme = dataset.polyfit(dim="year", deg=1)
        ext_key = list(fit_extreme.data_vars)[0]
        trend_vals = xr.polyval(dataset.year, fit_extreme[ext_key]).values
        ax2.plot(years_dt, trend_vals, linestyle=":", color=trend_color, linewidth=2, label=label_name)

    ax2.set_ylabel("Net Monthly Flux (ppm/month)")
    ax2.set_xlabel("Model Timeline")
    ax2.legend(loc="upper left")
    ax2.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.show()


def plot_regional_co2_anomalies(data, box):
    """
    Subtracts the global atmospheric mean from the local box mean to isolate 
    the true regional source/sink footprint, free from global mixing bias.
    """
    # 1. Calculate the raw Global Mean over time
    global_mean = data["CO2"].mean(dim=['lat', 'lon'])
    
    # 2. Isolate the local box and calculate the local mean
    data_box = data.sel(lat=slice(box.lat0, box.lat1), lon=slice(box.lon0, box.lon1))
    local_mean = data_box["CO2"].mean(dim=['lat', 'lon'])

    # 3. STRIP THE BACKGROUND MIXING: Calculate the anomaly footprint
    # (No .diff() is needed here; the subtraction naturally detrends the data)
    regional_anomaly_raw = local_mean - global_mean
    
    # Convert the anomaly array to ppm unit values
    regional_anomaly = convert_ppm(regional_anomaly_raw, key=None)

    # 5. Extract seasonal anomaly behaviors
    yearly_source_anomaly = regional_anomaly.groupby('time.year').max(dim='time')
    yearly_sink_anomaly = regional_anomaly.groupby('time.year').min(dim='time')
    years_dt = [np.datetime64(f"{int(y)}-06-15") for y in yearly_source_anomaly.year.values]

    # 6. Plotting
    fig, ax = plt.subplots(figsize=(14, 7))
    
    # Draw a bold line at 0.0 representing the Global Average Baseline
    ax.axhline(0, color='black', linestyle='-', linewidth=2, label="Global Average Baseline")

    # Plot local offsets
    ax.plot(years_dt, yearly_source_anomaly.values, marker='o', color='tab:red', linewidth=2, label="Local Winter Source Magnitude")
    ax.plot(years_dt, yearly_sink_anomaly.values, marker='s', color='tab:green', linewidth=2, label="Local Summer Sink Magnitude")

    # Add trends to see if the local behavior is shifting over the decades
    for dataset, color, name in [(yearly_source_anomaly, 'darkred', 'Source Intensity Trend'), (yearly_sink_anomaly, 'darkgreen', 'Sink Intensity Trend')]:
        fit = dataset.polyfit(dim="year", deg=1)
        trend = xr.polyval(dataset.year, fit.polyfit_coefficients)
        ax.plot(years_dt, trend.values, linestyle="--", color=color, alpha=0.8, label=name)

    ax.set_title(f"True Localized Carbon Footprint in {box.name} (Relative to Global Mean)", fontsize=14, fontweight='bold')
    ax.set_ylabel("Atmospheric Concentration Anomaly (ppm)")
    ax.set_xlabel("Model Year")
    ax.grid(True, alpha=0.3)
    ax.legend(loc="upper left")
    
    plt.tight_layout()
    plt.show()



def map_boxes(data, boxes):
    ax = map_setup()
    crs = ccrs.PlateCarree()

    num_boxes = len(boxes)
    colors = cm.get_cmap('tab10', num_boxes)

    # Loop and plot each box with an index to pick its unique color
    for idx, box in enumerate(boxes):
        # Pick the distinct color for this specific box index
        box_color = colors(idx)
        # Get bounds
        lon_min, lon_max = min(box.lon0, box.lon1), max(box.lon0, box.lon1)
        lat_min, lat_max = min(box.lat0, box.lat1), max(box.lat0, box.lat1)
        
        # Define the 4 corners of the box, closing the loop back at the start
        lons = [lon_min, lon_max, lon_max, lon_min, lon_min]
        lats = [lat_min, lat_min, lat_max, lat_max, lat_min]
        
        # Plot the path. Cartopy will automatically curve the lines to match the Robinson projection
        ax.plot(
            lons, lats, 
            color=box_color, 
            linewidth=2, 
            transform=crs
        )
        
        # Optional: Add text label
        ax.text(
            lon_min + 1, lat_min + 1, box.name,
            transform=crs, 
            color=box_color, 
            weight='bold'
        )

    plt.show()


