def plot_seasonal_amplitude(data, box, years):
    """
    Calculates and plots the annual seasonal amplitude (peak-to-trough max difference)
    of CO2 near the surface to track changes in source/sink behavior over time.
    """
    fig, ax = plt.subplots(figsize=(14, 6))
    
    # 1. Slice data to your region of interest
    data_box = data.sel(
        lat=slice(box.lat0, box.lat1),
        lon=slice(box.lon0, box.lon1),
    )

    # 2. Compute spatial mean and convert variations to ppm
    area_mean = data_box.mean(dim=['lat', 'lon'])
    area_delta = area_mean.diff(dim='time')
    area_ppm = convert_ppm(area_delta, key=None)["CO2"]

    # 3. Group by year and calculate peak-to-trough amplitude
    # We group by the 'time.year' virtual coordinate to isolate each year's cycle
    yearly_max = area_ppm.groupby('time.year').max(dim='time')
    yearly_min = area_ppm.groupby('time.year').min(dim='time')
    seasonal_amplitude = yearly_max - yearly_min

    # 4. Plot the historical amplitude trajectory
    amplitude_line = seasonal_amplitude.plot.line(
        linewidth=2, 
        label="Annual Seasonal Amplitude (Peak-to-Trough)", 
        ax=ax
    )
    line_color = amplitude_line[0].get_color()

    # 5. Fit a trendline to see if the cycle is widening or shrinking
    # polyfit requires a coordinate name, we use 'year' generated by the groupby
    fit_coefs = seasonal_amplitude.polyfit(dim="year", deg=1)
    amplitude_trend = xr.polyval(seasonal_amplitude.year, fit_coefs.polyfit_coefficients)
    
    amplitude_trend.plot.line(
        label="Amplitude Trend Line", 
        linestyle="--", 
        color=line_color, 
        alpha=0.8, 
        ax=ax
    )

    # 6. Formatting and Titles
    plt.title(f'CO2 Seasonal Amplitude Trend in {box.name} ({years[0]}-{years[-1]})')
    plt.xlabel('Year')
    plt.ylabel('Seasonal CO2 Amplitude (ppm)')
    plt.grid(True, linestyle=':', alpha=0.6)
    plt.legend()
    plt.show()


def plot_seasonal_amplitude_detrended(data, box, years):
    """
    Calculates and plots the true annual seasonal amplitude by detrending
    the data within each year first to eliminate background trend distortions.
    """
    fig, ax = plt.subplots(figsize=(14, 6))
    
    # 1. Slice data to your region of interest
    data_box = data.sel(
        lat=slice(box.lat0, box.lat1),
        lon=slice(box.lon0, box.lon1),
    )

    # 2. Compute spatial mean and convert variations to ppm
    area_mean = data_box.mean(dim=['lat', 'lon'])
    area_delta = area_mean.diff(dim='time')
    area_ppm = convert_ppm(area_delta, key=None)["CO2"]

    # 3. Custom function to cleanly strip the trend out of each individual year
    def detrend_yearly_block(group):
        # We need a continuous array of values, dropping any NaN values if present
        values = group.values
        if len(values) > 1:
            # Linear detrend strips out the downward or upward slant within these 12 months
            detrended_values = signal.detrend(values, type='linear')
            # Return a fresh xarray DataArray matching the original coordinate structure
            return xr.DataArray(detrended_values, coords=group.coords, dims=group.dims)
        return group

    # Apply the intra-annual detrending filter
    detrended_ppm = area_ppm.groupby('time.year').map(detrend_yearly_block)

    # 4. Group by year to extract true peaks, troughs, and amplitudes
    yearly_max = detrended_ppm.groupby('time.year').max(dim='time')
    yearly_min = detrended_ppm.groupby('time.year').min(dim='time')
    seasonal_amplitude = yearly_max - yearly_min

    # 5. Plot the historical amplitude trajectory
    amplitude_line = seasonal_amplitude.plot.line(
        linewidth=2, 
        label="True Annual Seasonal Amplitude (Detrended)", 
        ax=ax
    )
    line_color = amplitude_line[0].get_color()

    # 6. Fit a trendline to see if the cycle size is structurally changing
    fit_coefs = seasonal_amplitude.polyfit(dim="year", deg=1)
    amplitude_trend = xr.polyval(seasonal_amplitude.year, fit_coefs.polyfit_coefficients)
    
    amplitude_trend.plot.line(
        label="Amplitude Trend Line", 
        linestyle="--", 
        color=line_color, 
        alpha=0.8, 
        ax=ax
    )

    # 7. Formatting and Titles
    plt.title(f'True CO2 Seasonal Amplitude Trend in {box.name} ({years[0]}-{years[-1]})')
    plt.xlabel('Year')
    plt.ylabel('Detrended Seasonal CO2 Amplitude (ppm)')
    plt.grid(True, linestyle=':', alpha=0.6)
    plt.legend()
    plt.show()

    overall_flux_mean = area_ppm.mean().values
    print(f"Overall Net Monthly Flux Mean {box.name}: {overall_flux_mean:.4f} ppm")


