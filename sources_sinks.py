class CoordinateBox:
    def __init__(self, name, lat0, lat1, lon0, lon1):
        self.name = name
        self.lat0 = lat0
        self.lat1 = lat1
        self.lon0 = lon0
        self.lon1 = lon1

    def __repr__(self):
        return f"CoordinateBox(name={self.name}, lat0={self.lat0}, lat1={self.lat1}, lon0={self.lon0}, lon1={self.lon1})"
    

def remove_long_term_trend(data, key):
    fit = data.polyfit(dim="time", deg=2)
    trend = xr.polyval(data.time, fit.polyfit_coefficients)
    detrended = data - trend
    return detrended


